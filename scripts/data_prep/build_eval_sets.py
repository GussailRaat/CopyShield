#!/usr/bin/env python3
"""
build_eval_sets.py
==================
Build the four evaluation JSON files in data/:

  eval_literal.json              200 literal prefix->reference pairs
                                 (40 per book; 150-token prefix, 200-token reference).
                                 Fully deterministic given a seed and the LLaMA tokenizer.

  eval_nonliteral.json            50 non-literal {question, reference} pairs
                                 (10 per book). question = narrative question
                                 generated by an LLM; reference = the matching
                                 passage from the book.

  eval_nonliteral_extra150.json  150 additional non-literal pairs
                                 (30 per book) -- same procedure, larger N.

  qa_book_questions.json          50 QA {question, reference} pairs
                                 (10 per book). reference = short factual answer
                                 (1-3 sentences), NOT a verbatim book passage.

Inputs:
  data/cleaned_books/<book>.txt  Per-book cleaned text (produced by prepare_corpora.py)

LLM question generation uses the Anthropic API (already in requirements.txt).
Pass --seed_questions <path> to skip the API call and reuse questions from an
existing JSON file.

Usage:
    # Re-generate all four files from scratch (requires ANTHROPIC_API_KEY)
    python scripts/data_prep/build_eval_sets.py

    # Re-build only the literal set (no API needed)
    python scripts/data_prep/build_eval_sets.py --only literal

    # Re-build non-literal eval using existing questions, just refresh references
    python scripts/data_prep/build_eval_sets.py --only nonliteral \\
        --seed_questions data/eval_nonliteral.json

Requires:
    transformers (for LLaMA tokenizer)
    anthropic    (for question generation)
"""

import argparse
import json
import os
import random
import re
import sys
from pathlib import Path

# ---------------------------------------------------------------------------
# Books -- slugs must match prepare_corpora.py
# ---------------------------------------------------------------------------

BOOKS = [
    ("pride_and_prejudice", "Pride and Prejudice"),
    ("frankenstein",        "Frankenstein"),
    ("dracula",             "Dracula"),
    ("moby_dick",           "Moby-Dick"),
    ("sherlock_holmes",     "The Adventures of Sherlock Holmes"),
]

# ---------------------------------------------------------------------------
# 1. Literal eval -- deterministic token sampling
# ---------------------------------------------------------------------------

def load_tokenizer(model_id: str):
    from transformers import AutoTokenizer
    return AutoTokenizer.from_pretrained(model_id, use_fast=True)


def sample_literal_pairs(
    book_slug: str,
    book_text: str,
    tokenizer,
    n_samples: int,
    prefix_tokens: int,
    reference_tokens: int,
    rng: random.Random,
) -> list[dict]:
    """Sample N (prefix, reference) pairs from a single book.
    Each prefix is `prefix_tokens` long; reference is the subsequent
    `reference_tokens` long. Sampling positions are uniformly random within
    valid book boundaries.
    """
    token_ids = tokenizer.encode(book_text, add_special_tokens=False)
    needed = prefix_tokens + reference_tokens
    max_start = len(token_ids) - needed
    if max_start <= 0:
        raise ValueError(f"Book '{book_slug}' too short ({len(token_ids)} tokens) for prefix={prefix_tokens} + reference={reference_tokens}")

    starts = rng.sample(range(0, max_start), n_samples)
    out = []
    for i, start in enumerate(sorted(starts)):
        prefix_ids    = token_ids[start : start + prefix_tokens]
        reference_ids = token_ids[start + prefix_tokens : start + needed]
        out.append({
            "id":        None,  # filled by caller (so IDs are sequential across books)
            "book":      book_slug,
            "prefix":    tokenizer.decode(prefix_ids,    skip_special_tokens=True),
            "reference": tokenizer.decode(reference_ids, skip_special_tokens=True),
        })
    return out


def build_literal_eval(
    cleaned_dir: Path,
    tokenizer_id: str,
    out_path: Path,
    per_book: int = 40,
    prefix_tokens: int = 150,
    reference_tokens: int = 200,
    seed: int = 42,
) -> None:
    print(f"\n[literal] Loading tokenizer: {tokenizer_id}")
    tokenizer = load_tokenizer(tokenizer_id)
    rng = random.Random(seed)

    all_records = []
    for slug, _title in BOOKS:
        book_path = cleaned_dir / f"{slug}.txt"
        text = book_path.read_text(encoding="utf-8")
        records = sample_literal_pairs(
            slug, text, tokenizer, per_book, prefix_tokens, reference_tokens, rng,
        )
        print(f"  {slug}: {len(records)} pairs")
        all_records.extend(records)

    for i, rec in enumerate(all_records):
        rec["id"] = f"lit_{i:03d}"

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(all_records, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"  -> {out_path} ({len(all_records)} records)")


# ---------------------------------------------------------------------------
# 2. Non-literal eval -- LLM-generated questions + corpus-matched references
# ---------------------------------------------------------------------------

NONLITERAL_PROMPT = """You are helping build an evaluation set for a study of copyright suppression in language models.

For the novel "{title}", generate {n} distinct narrative questions of the form
"Describe ...", "What happens when ...", "How does X react to ...", etc. Each question
should ask about a specific scene or moment in the book, NOT a high-level theme.

For each question, also provide a short anchor phrase (5-15 words) -- an exact
verbatim phrase from the book that marks where the answer begins. The anchor
must be copied EXACTLY from the source text.

Return ONLY a JSON array (no prose, no markdown fences) with this schema:
[
  {{"question": "...", "anchor": "..."}},
  ...
]
"""


QA_PROMPT = """You are helping build a factual QA evaluation set about the novel "{title}".

Generate {n} distinct factual questions of the form "Who is X?", "What is X?",
"Where does X happen?", etc. Each question must have a SHORT, factually correct
answer (1-3 sentences, 30-60 words) that an educated reader could write from
memory -- DO NOT quote the book verbatim.

Return ONLY a JSON array (no prose, no markdown fences) with this schema:
[
  {{"question": "...", "answer": "..."}},
  ...
]
"""


def call_anthropic_json(prompt: str, model: str = "claude-sonnet-4-5"):
    """Call Claude and parse the response as a JSON array.
    Strips common markdown wrappers if the model still emits them.
    """
    import anthropic
    client = anthropic.Anthropic()
    msg = client.messages.create(
        model=model,
        max_tokens=8192,
        messages=[{"role": "user", "content": prompt}],
    )
    raw = msg.content[0].text.strip()
    # Strip ```json ... ``` wrapper if present
    raw = re.sub(r"^```(?:json)?\s*", "", raw)
    raw = re.sub(r"\s*```$", "", raw)
    return json.loads(raw)


def find_anchor_passage(book_text: str, anchor: str, window: int = 1500) -> str | None:
    """Locate `anchor` (case-insensitive) in book_text and return a passage
    starting at that point of approximately `window` characters.
    Returns None if not found.
    """
    idx = book_text.lower().find(anchor.lower())
    if idx < 0:
        # Try a relaxed match on the first 6 words of the anchor
        words = anchor.split()
        if len(words) >= 4:
            short = " ".join(words[:4])
            idx = book_text.lower().find(short.lower())
    if idx < 0:
        return None
    return book_text[idx : idx + window].strip()


def build_nonliteral_eval(
    cleaned_dir: Path,
    out_path: Path,
    per_book: int,
    id_prefix: str,
    seed_questions_path: Path | None,
    model: str,
) -> None:
    label = out_path.stem
    print(f"\n[{label}] target: {per_book} per book")
    book_texts = {slug: (cleaned_dir / f"{slug}.txt").read_text(encoding="utf-8")
                  for slug, _ in BOOKS}

    if seed_questions_path:
        print(f"  Reusing questions from {seed_questions_path}")
        seed_records = json.loads(seed_questions_path.read_text(encoding="utf-8"))
        per_book_records = {slug: [] for slug, _ in BOOKS}
        for r in seed_records:
            per_book_records.setdefault(r["book"], []).append(r)
    else:
        per_book_records = {}
        for slug, title in BOOKS:
            print(f"  Generating {per_book} questions for {title} via Anthropic API...")
            items = call_anthropic_json(NONLITERAL_PROMPT.format(title=title, n=per_book), model=model)
            per_book_records[slug] = [
                {"book": slug, "question": x["question"], "anchor": x.get("anchor", "")}
                for x in items[:per_book]
            ]

    all_records = []
    for slug, _ in BOOKS:
        for rec in per_book_records.get(slug, [])[:per_book]:
            ref = rec.get("reference")
            if not ref:
                anchor = rec.get("anchor") or rec.get("question", "")
                ref = find_anchor_passage(book_texts[slug], anchor) or ""
            all_records.append({
                "id":        None,
                "book":      slug,
                "question":  rec["question"],
                "reference": ref,
            })

    for i, rec in enumerate(all_records):
        rec["id"] = f"{id_prefix}_{i:03d}"

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(all_records, indent=2, ensure_ascii=False), encoding="utf-8")
    missing = sum(1 for r in all_records if not r["reference"])
    print(f"  -> {out_path} ({len(all_records)} records; {missing} without reference)")


# ---------------------------------------------------------------------------
# 3. QA eval -- LLM-generated factual Q+A pairs
# ---------------------------------------------------------------------------

def build_qa_eval(
    out_path: Path,
    per_book: int,
    id_prefix: str,
    seed_questions_path: Path | None,
    model: str,
) -> None:
    print(f"\n[qa] target: {per_book} per book")
    if seed_questions_path:
        print(f"  Reusing questions from {seed_questions_path}")
        seed_records = json.loads(seed_questions_path.read_text(encoding="utf-8"))
        per_book_records = {slug: [] for slug, _ in BOOKS}
        for r in seed_records:
            per_book_records.setdefault(r["book"], []).append(r)
        all_records = []
        for slug, _ in BOOKS:
            for rec in per_book_records.get(slug, [])[:per_book]:
                all_records.append({
                    "id":        None,
                    "book":      slug,
                    "question":  rec["question"],
                    "reference": rec.get("reference") or rec.get("answer", ""),
                })
    else:
        all_records = []
        for slug, title in BOOKS:
            print(f"  Generating {per_book} QA pairs for {title} via Anthropic API...")
            items = call_anthropic_json(QA_PROMPT.format(title=title, n=per_book), model=model)
            for x in items[:per_book]:
                all_records.append({
                    "id":        None,
                    "book":      slug,
                    "question":  x["question"],
                    "reference": x["answer"],
                })

    for i, rec in enumerate(all_records):
        rec["id"] = f"{id_prefix}_{i:03d}"

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(all_records, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"  -> {out_path} ({len(all_records)} records)")


# ---------------------------------------------------------------------------
# Driver
# ---------------------------------------------------------------------------

def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--cleaned_dir",     default="data/cleaned_books",
                   help="Directory of per-book cleaned .txt files")
    p.add_argument("--data_dir",        default="data",
                   help="Output directory for eval JSONs")
    p.add_argument("--tokenizer",       default="meta-llama/Llama-3.1-8B",
                   help="HF tokenizer for literal token sampling")
    p.add_argument("--anthropic_model", default="claude-sonnet-4-5",
                   help="Anthropic model for question generation")
    p.add_argument("--seed",            type=int, default=42)

    p.add_argument("--only", choices=["literal", "nonliteral", "nonliteral_extra", "qa"],
                   help="Build only one of the four eval sets")

    p.add_argument("--seed_questions_nonliteral",       type=Path, default=None,
                   help="Path to existing JSON to reuse non-literal questions from (skip LLM)")
    p.add_argument("--seed_questions_nonliteral_extra", type=Path, default=None,
                   help="Path to existing JSON to reuse extra-150 questions from (skip LLM)")
    p.add_argument("--seed_questions_qa",               type=Path, default=None,
                   help="Path to existing JSON to reuse QA questions from (skip LLM)")
    args = p.parse_args()

    cleaned_dir = Path(args.cleaned_dir)
    data_dir    = Path(args.data_dir)

    if args.only in (None, "literal"):
        build_literal_eval(
            cleaned_dir, args.tokenizer,
            data_dir / "eval_literal.json",
            per_book=40, prefix_tokens=150, reference_tokens=200, seed=args.seed,
        )

    if args.only in (None, "nonliteral"):
        build_nonliteral_eval(
            cleaned_dir,
            data_dir / "eval_nonliteral.json",
            per_book=10, id_prefix="nonlit",
            seed_questions_path=args.seed_questions_nonliteral,
            model=args.anthropic_model,
        )

    if args.only in (None, "nonliteral_extra"):
        build_nonliteral_eval(
            cleaned_dir,
            data_dir / "eval_nonliteral_extra150.json",
            per_book=30, id_prefix="nonlit_extra",
            seed_questions_path=args.seed_questions_nonliteral_extra,
            model=args.anthropic_model,
        )

    if args.only in (None, "qa"):
        build_qa_eval(
            data_dir / "qa_book_questions.json",
            per_book=10, id_prefix="qa_book",
            seed_questions_path=args.seed_questions_qa,
            model=args.anthropic_model,
        )

    print("\nDone.")


if __name__ == "__main__":
    sys.exit(main())
